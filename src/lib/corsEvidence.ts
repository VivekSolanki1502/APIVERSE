/**
 * Evidence-backed CORS reports. A report is only produced for outcomes that actually prove
 * something about browser access:
 *  - "readable": the browser delivered a response to a page (any HTTP status), so CORS allowed it.
 *  - "blocked-confirmed": the browser request failed AND the person says the same request works
 *    outside a browser (curl, Postman). Without that confirmation a failure is inconclusive,
 *    because offline networks, DNS errors, ad blockers and extensions look identical to CORS.
 * Nothing is sent anywhere automatically: the output is a pre-filled GitHub issue link the
 * person reviews and submits themselves. Query values and credentials are never included.
 */
import type { ApiEntry, CorsResult } from '../types/catalog';
import type { ExecuteResult } from './request';

export interface CorsObservation {
  apiId: string;
  apiName: string;
  /** Origin + path only. Query values are removed. */
  testedUrl: string;
  testedOn: string;
  browser: string;
  result: CorsResult;
  notes: string | null;
}

export type ObservationOutcome =
  | { ok: true; observation: CorsObservation }
  | { ok: false; reason: string };

export function detectBrowser(ua: string): string {
  const m =
    /(Edg)\/(\d+)/.exec(ua) ? ['Edge', /(Edg)\/(\d+)/.exec(ua)![2]] :
    /(OPR)\/(\d+)/.exec(ua) ? ['Opera', /(OPR)\/(\d+)/.exec(ua)![2]] :
    /(Firefox)\/(\d+)/.exec(ua) ? ['Firefox', /(Firefox)\/(\d+)/.exec(ua)![2]] :
    /(Chrome|Chromium)\/(\d+)/.exec(ua) ? ['Chrome', /(Chrome|Chromium)\/(\d+)/.exec(ua)![2]] :
    /Version\/(\d+).*Safari/.exec(ua) ? ['Safari', /Version\/(\d+).*Safari/.exec(ua)![1]] :
    null;
  return m ? `${m[0]} ${m[1]}` : 'Unknown browser';
}

/** Keep the origin and path and the NAMES of query parameters; drop every value. */
export function redactForReport(rawUrl: string): string {
  try {
    const u = new URL(rawUrl);
    const names = [...new Set([...u.searchParams.keys()])];
    return `${u.origin}${u.pathname}${names.length ? `?${names.map((n) => `${n}=…`).join('&')}` : ''}`;
  } catch {
    return '';
  }
}

export function buildObservation(input: {
  api: ApiEntry;
  requestUrl: string;
  result: ExecuteResult;
  /** The person confirms the same request works outside a browser. */
  worksOutsideBrowser: boolean;
  userAgent: string;
  today: string;
  notes?: string;
}): ObservationOutcome {
  const { api, result } = input;
  const base = {
    apiId: api.id,
    apiName: api.name,
    testedUrl: redactForReport(input.requestUrl),
    testedOn: input.today,
    browser: detectBrowser(input.userAgent),
    notes: input.notes?.trim() ? input.notes.trim().slice(0, 300) : null,
  };
  if (!base.testedUrl) return { ok: false, reason: 'The request URL is not valid.' };
  if (result.ok) return { ok: true, observation: { ...base, result: 'readable' } };
  if (result.kind !== 'cors-or-network') {
    return { ok: false, reason: 'This failure is not a CORS or network failure (for example timeout, cancelled or blocked address), so it says nothing about CORS support.' };
  }
  if (!input.worksOutsideBrowser) {
    return { ok: false, reason: 'A browser failure alone is inconclusive: offline networks, DNS errors, ad blockers and CORS look the same. Confirm the request works outside a browser (curl or Postman) to report it as blocked.' };
  }
  return { ok: true, observation: { ...base, result: 'blocked-confirmed' } };
}

/** The catalog entry maintainers would add, ready to paste into corsEvidence. */
export function proposedEntry(o: CorsObservation) {
  return { testedOn: o.testedOn, browser: o.browser, result: o.result, notes: o.notes, reportUrl: null as string | null };
}

export function buildIssueUrl(repoUrl: string, o: CorsObservation): string {
  const title = `CORS report: ${o.apiName} (${o.result})`;
  const body = [
    `API id: ${o.apiId}`,
    `Result: ${o.result}`,
    `Browser: ${o.browser}`,
    `Tested on: ${o.testedOn}`,
    `Request (query values removed): ${o.testedUrl}`,
    o.notes ? `Notes: ${o.notes}` : 'Notes: none',
    '',
    'Proposed corsEvidence entry:',
    '```json',
    JSON.stringify(proposedEntry(o), null, 2),
    '```',
    '',
    'Generated by the APIverse playground. No API keys, cookies or response data are included. A maintainer will re-check before changing the catalog.',
  ].join('\n');
  const q = new URLSearchParams({ template: 'cors-report.yml', labels: 'cors-report', title, report: body });
  return `${repoUrl}/issues/new?${q.toString()}`;
}
